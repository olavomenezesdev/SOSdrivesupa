create table public.provider_earnings (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    service_request_id bigint not null unique
        references public.service_requests (id) on delete restrict,
    payment_id bigint not null unique
        references public.service_request_payments (id) on delete restrict,
    provider_id uuid not null references auth.users (id) on delete restrict,
    amount numeric(12, 2) not null check (amount > 0)
);

create index provider_earnings_provider_idx
    on public.provider_earnings (provider_id, created_at desc);

alter table public.provider_earnings enable row level security;
revoke all on public.provider_earnings from anon, authenticated;
grant select on public.provider_earnings to service_role;

create or replace function public.record_provider_earning_on_payment_confirmation()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    request_provider_id uuid;
begin
    if new.status <> 'confirmed' then
        return new;
    end if;

    if tg_op = 'UPDATE' and old.status = 'confirmed' then
        return new;
    end if;

    select provider_id
    into request_provider_id
    from public.service_requests
    where id = new.service_request_id;

    if request_provider_id is null then
        raise exception 'Confirmed payment has no service provider';
    end if;

    if new.provider_id is not null and new.provider_id <> request_provider_id then
        raise exception 'Payment provider does not match service request provider';
    end if;

    insert into public.provider_earnings (
        service_request_id,
        payment_id,
        provider_id,
        amount
    )
    values (
        new.service_request_id,
        new.id,
        request_provider_id,
        new.amount
    )
    on conflict (service_request_id) do nothing;

    return new;
end;
$$;

revoke all on function public.record_provider_earning_on_payment_confirmation()
    from public, anon, authenticated;

create trigger service_request_payment_record_provider_earning
after insert or update of status on public.service_request_payments
for each row
execute function public.record_provider_earning_on_payment_confirmation();

insert into public.provider_earnings (
    service_request_id,
    payment_id,
    provider_id,
    amount
)
select
    payment.service_request_id,
    payment.id,
    request.provider_id,
    payment.amount
from public.service_request_payments payment
join public.service_requests request
    on request.id = payment.service_request_id
where payment.status = 'confirmed'
  and payment.amount > 0
  and request.provider_id is not null
  and (payment.provider_id is null or payment.provider_id = request.provider_id)
on conflict (service_request_id) do nothing;
