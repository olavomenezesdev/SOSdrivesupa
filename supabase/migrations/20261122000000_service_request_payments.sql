create table public.service_request_payments (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    service_request_id bigint not null unique
        references public.service_requests (id) on delete restrict,
    customer_id uuid not null references auth.users (id) on delete restrict,
    provider_id uuid references auth.users (id) on delete set null,
    gateway text not null default 'asaas',
    gateway_payment_id text,
    payment_method text not null check (
        payment_method in ('pix', 'credit_card', 'debit_card', 'machine')
    ),
    amount numeric(12, 2) not null check (amount >= 0),
    status text not null default 'pending' check (
        status in ('pending', 'confirmed', 'failed', 'expired', 'cancelled')
    ),
    pix_payload text,
    pix_qr_code text,
    expires_at timestamptz,
    gateway_payload jsonb not null default '{}'::jsonb
);

create index service_request_payments_customer_idx
    on public.service_request_payments (customer_id, created_at desc);
create index service_request_payments_gateway_idx
    on public.service_request_payments (gateway, gateway_payment_id);

create trigger service_request_payments_set_updated_at
before update on public.service_request_payments
for each row execute function public.set_updated_at();

alter table public.service_request_payments enable row level security;

revoke all on public.service_request_payments from anon, authenticated;
grant select, insert, update on public.service_request_payments to service_role;
grant usage, select on sequence public.service_request_payments_id_seq to service_role;

create policy "Customers can view their own payments"
on public.service_request_payments
for select
to authenticated
using (customer_id = auth.uid());

create table public.service_request_reviews (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    service_request_id bigint not null
        references public.service_requests (id) on delete restrict,
    reviewer_id uuid not null references auth.users (id) on delete restrict,
    reviewee_id uuid not null references auth.users (id) on delete restrict,
    rating integer not null check (rating between 1 and 5),
    comment text not null default '',
    unique (service_request_id, reviewer_id)
);

create index service_request_reviews_reviewee_idx
    on public.service_request_reviews (reviewee_id, created_at desc);
create index service_request_reviews_request_idx
    on public.service_request_reviews (service_request_id);

alter table public.service_request_reviews enable row level security;

revoke all on public.service_request_reviews from anon, authenticated;
grant select on public.service_request_reviews to authenticated;
grant select, insert on public.service_request_reviews to service_role;

create policy "Participants can view reviews for their requests"
on public.service_request_reviews
for select
to authenticated
using (
    exists (
        select 1
        from public.service_requests request
        where request.id = service_request_reviews.service_request_id
          and (request.user_id = auth.uid() or request.provider_id = auth.uid())
    )
);
