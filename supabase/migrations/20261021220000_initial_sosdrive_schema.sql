create table public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    created_at timestamptz not null default now(),
    full_name text not null default '',
    role text not null check (role in ('cliente', 'prestador')),
    cpf text not null default '',
    telefone text not null default '',
    foto_perfil text not null default '',
    is_demo boolean not null default false
);

create table public.vehicles (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id) on delete restrict,
    brand text not null,
    model text not null,
    plate text not null,
    year integer not null,
    color text not null
);

create index vehicles_user_id_idx on public.vehicles (user_id);

create table public.service_requests (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    user_id uuid not null references auth.users (id) on delete restrict,
    provider_id uuid references auth.users (id) on delete set null,
    vehicle_id bigint not null references public.vehicles (id) on delete restrict,
    service_type text not null,
    latitude numeric(10, 7) not null check (latitude between -90 and 90),
    longitude numeric(10, 7) not null check (longitude between -180 and 180),
    estimated_price numeric(12, 2) not null check (estimated_price >= 0),
    distance_km numeric(10, 3) not null check (distance_km >= 0),
    status text not null default 'pending'
);

create index service_requests_user_id_idx on public.service_requests (user_id);
create index service_requests_provider_id_idx on public.service_requests (provider_id);
create index service_requests_created_at_idx on public.service_requests (created_at desc);
create index service_requests_pending_idx
    on public.service_requests (created_at desc)
    where status = 'pending' and provider_id is null;

create table public.service_request_acceptance (
    id bigint generated by default as identity primary key,
    service_request_id bigint not null unique
        references public.service_requests (id) on delete cascade,
    provider_id uuid not null references auth.users (id) on delete restrict,
    created_at timestamptz not null default now()
);

create table public.service_messages (
    id bigint generated by default as identity primary key,
    service_request_id bigint not null
        references public.service_requests (id) on delete cascade,
    sender_id uuid not null references auth.users (id) on delete restrict,
    message_text text not null check (length(btrim(message_text)) > 0),
    created_at timestamptz not null default now()
);

create index service_messages_request_created_idx
    on public.service_messages (service_request_id, created_at asc);
create index service_messages_sender_id_idx on public.service_messages (sender_id);

create table public.event_log (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    user_id uuid references auth.users (id) on delete set null,
