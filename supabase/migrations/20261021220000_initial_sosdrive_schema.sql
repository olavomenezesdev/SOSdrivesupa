create or replace function public.advance_imported_id_sequences()
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
    table_name text;
    sequence_name text;
    max_id bigint;
begin
    foreach table_name in array array[
        'vehicles',
        'service_requests',
        'service_request_acceptance',
        'service_messages',
        'event_log'
    ]
    loop
        sequence_name := pg_catalog.pg_get_serial_sequence(
            pg_catalog.format('public.%I', table_name),
            'id'
        );
        execute pg_catalog.format('select max(id) from public.%I', table_name)
            into max_id;
        if sequence_name is not null then
            perform pg_catalog.setval(
                sequence_name,
                coalesce(max_id, 1),
                max_id is not null
            );
        end if;
    end loop;
end;
$$;

