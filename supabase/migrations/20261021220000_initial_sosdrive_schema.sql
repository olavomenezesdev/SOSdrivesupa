create or replace function public.create_service_request(
    p_service_type text,
    p_vehicle_id bigint,
    p_latitude numeric,
    p_longitude numeric
)
returns public.service_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
    actor_id uuid := auth.uid();
    actor_role text;
    vehicle_owner uuid;
    base_price numeric;
    price_per_km numeric;
    distance numeric;
    created_request public.service_requests;
begin
    if actor_id is null then
        raise exception 'Authentication required' using errcode = '42501';
    end if;

    select profile.role into actor_role
    from public.profiles profile
    where profile.id = actor_id;
    if actor_role is distinct from 'cliente' then
        raise exception 'Only clients can create service requests' using errcode = '42501';
    end if;

    select vehicle.user_id into vehicle_owner
    from public.vehicles vehicle
    where vehicle.id = p_vehicle_id;
    if vehicle_owner is distinct from actor_id then
        raise exception 'Vehicle is not owned by the authenticated user' using errcode = '42501';
    end if;

    if p_latitude is null or p_latitude not between -90 and 90
       or p_longitude is null or p_longitude not between -180 and 180 then
        raise exception 'Invalid coordinates' using errcode = '22023';
    end if;

    case p_service_type
        when 'tire' then
            base_price := 40.0;
            price_per_km := 2.5;
        when 'battery' then
            base_price := 60.0;
            price_per_km := 2.5;
        when 'mechanical' then
            base_price := 80.0;
            price_per_km := 3.0;
        when 'fuel' then
            base_price := 35.0;
            price_per_km := 2.0;
        else
            raise exception 'Unsupported service type' using errcode = '22023';
    end case;

    distance := 6371.0 * acos(
        least(
            1.0,
            greatest(
                -1.0,
                sin(radians(p_latitude::double precision))
                    * sin(radians(-23.5505::double precision))
                + cos(radians(p_latitude::double precision))
                    * cos(radians(-23.5505::double precision))
                    * cos(radians((p_longitude - (-46.6333))::double precision))
            )
        )
    );

    insert into public.service_requests (
        user_id, vehicle_id, service_type, latitude, longitude,
        estimated_price, distance_km, status
    )
    values (
        actor_id, p_vehicle_id, p_service_type, p_latitude, p_longitude,
        round(base_price + distance * price_per_km, 2), round(distance, 3), 'pending'
    )
    returning * into created_request;

    return created_request;
end;
$$;

create or replace function public.list_pending_service_requests()
returns table (
    id bigint,
    created_at timestamptz,
    user_id uuid,
    vehicle_id bigint,
    service_type text,
    latitude numeric,
    longitude numeric,
    estimated_price numeric,
    distance_km numeric,
    status text,
    user_name text,
    vehicle_brand text,
    vehicle_model text,
    vehicle_plate text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
    if not exists (
        select 1
        from public.profiles profile
        where profile.id = auth.uid() and profile.role = 'prestador'
    ) then
        raise exception 'Only providers can list pending service requests'
            using errcode = '42501';
    end if;

    return query
    select request.id, request.created_at, request.user_id, request.vehicle_id,
           request.service_type, request.latitude, request.longitude,
           request.estimated_price, request.distance_km, request.status,
           profile.full_name, vehicle.brand, vehicle.model, vehicle.plate
    from public.service_requests request
    join public.profiles profile on profile.id = request.user_id
    join public.vehicles vehicle on vehicle.id = request.vehicle_id
    where request.status = 'pending' and request.provider_id is null
    order by request.created_at desc;
end;
$$;

create or replace function public.accept_service_request(p_request_id bigint)
returns public.service_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
    actor_id uuid := auth.uid();
    actor_role text;
    accepted_request public.service_requests;
begin
    if actor_id is null then
        raise exception 'Authentication required' using errcode = '42501';
    end if;

    select profile.role into actor_role
    from public.profiles profile
    where profile.id = actor_id;
    if actor_role is distinct from 'prestador' then
        raise exception 'Only providers can accept service requests' using errcode = '42501';
    end if;

    update public.service_requests
    set provider_id = actor_id, status = 'accepted'
    where id = p_request_id and status = 'pending' and provider_id is null
    returning * into accepted_request;

    if not found then
        raise exception 'Service request is no longer available' using errcode = '40001';
    end if;

    insert into public.service_request_acceptance (service_request_id, provider_id)
    values (accepted_request.id, actor_id);

    return accepted_request;
end;
$$;

create or replace function public.release_service_request(p_request_id bigint)
returns public.service_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
    actor_id uuid := auth.uid();
    actor_role text;
    released_request public.service_requests;
begin
    if actor_id is null then
        raise exception 'Authentication required' using errcode = '42501';
    end if;

    select profile.role into actor_role
    from public.profiles profile
    where profile.id = actor_id;
    if actor_role is distinct from 'prestador' then
        raise exception 'Only providers can release service requests' using errcode = '42501';
    end if;

    update public.service_requests
    set provider_id = null, status = 'pending'
    where id = p_request_id
      and provider_id = actor_id
      and status in ('accepted', 'in_progress')
    returning * into released_request;

    if not found then
        raise exception 'Service request cannot be released by this provider'
            using errcode = '42501';
    end if;

    delete from public.service_request_acceptance
    where service_request_id = p_request_id and provider_id = actor_id;

    return released_request;
end;
$$;

create or replace function public.complete_service_request(p_request_id bigint)
returns public.service_requests
language plpgsql
security definer
set search_path = ''
as $$
declare
    actor_id uuid := auth.uid();
    actor_role text;
    completed_request public.service_requests;
begin
    if actor_id is null then
        raise exception 'Authentication required' using errcode = '42501';
    end if;

    select profile.role into actor_role
    from public.profiles profile
    where profile.id = actor_id;
    if actor_role is distinct from 'prestador' then
        raise exception 'Only providers can complete service requests' using errcode = '42501';
    end if;

    update public.service_requests
    set status = 'completed'
    where id = p_request_id
      and provider_id = actor_id
      and status in ('accepted', 'in_progress')
    returning * into completed_request;

    if not found then
        raise exception 'Service request cannot be completed by this provider'
            using errcode = '42501';
    end if;

    return completed_request;
end;
$$;

